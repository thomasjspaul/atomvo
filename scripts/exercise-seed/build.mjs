// Builds migrations/0019_exercise_catalog_more.sql from exercises.txt.
// Run: node scripts/exercise-seed/build.mjs  (only needed if the list changes
// before the migration is applied anywhere — migrations are immutable after).
import { readFileSync, writeFileSync } from "node:fs";

const OUT = "migrations/0019_exercise_catalog_more.sql";
const MUSCLES = "chest back shoulders biceps triceps forearms core quads hamstrings glutes calves cardio".split(" ");
const EQUIP = "barbell dumbbell kettlebell cable machine smith bodyweight band other".split(" ");
const CATS = ["compound", "isolation", "cardio"];

// Mirrors normalizeExerciseName in worker/util.ts.
const norm = (s) =>
  String(s).toLowerCase().normalize("NFKD").replace(/[^\p{L}\p{N}]+/gu, " ")
    .replace(/\s+/g, " ").trim().replace(/^the /, "");
const q = (s) => (s == null ? "NULL" : `'${String(s).replace(/'/g, "''")}'`);

const existing = new Set(
  [...readFileSync("migrations/0015_exercise_catalog_seed.sql", "utf8").matchAll(/^\s+\('seed_[^']*', '(?:[^']|'')*', '([^']*)'/gm)].map((m) => m[1]),
);
const seen = new Set();
const rows = [];
for (const line of readFileSync(new URL("./exercises.txt", import.meta.url), "utf8").split("\n")) {
  if (!line.trim() || line.startsWith("#")) continue;
  const [name, muscle, equipment, category, aliases = ""] = line.split("|").map((s) => s.trim());
  const n = norm(name);
  if (!MUSCLES.includes(muscle) || !EQUIP.includes(equipment) || !CATS.includes(category))
    throw new Error(`bad row: ${line}`);
  if (existing.has(n)) { console.warn("skip, already seeded:", name); continue; }
  if (seen.has(n)) throw new Error(`duplicate: ${name}`);
  seen.add(n);
  const al = aliases.split(";").map((s) => s.trim()).filter(Boolean);
  const id = "seed_" + n.replace(/ /g, "_");
  rows.push(`  (${q(id)}, ${q(name)}, ${q(n)}, ${al.length ? q(JSON.stringify(al)) : "NULL"}, ${q(muscle)}, ${q(equipment)}, ${q(category)})`);
}

writeFileSync(OUT, `-- ${rows.length} more exercises for the catalog, so search and the body-area /
-- equipment lists are answered locally without waiting on AI. Generated by
-- scripts/exercise-seed/build.mjs from exercises.txt. INSERT OR IGNORE: an
-- exercise someone already added (same norm_name) keeps its existing row.

INSERT OR IGNORE INTO exercise_catalog
  (id, canonical_name, norm_name, aliases_json, primary_muscle, equipment, category)
VALUES
${rows.join(",\n")};
`);
console.log("wrote", OUT, rows.length, "rows");
